NOTEBOOK_REDIRECT = '''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta http-equiv="refresh" content="0; url=/portfolio/?edition=expanded" />
  <link rel="canonical" href="/portfolio/" />
  <title>The Notebook — SDIT</title>
</head>
<body>
  <p>Your Notebook is the Expanded Edition of your <a href="/portfolio/?edition=expanded">Portfolio</a>.</p>
</body>
</html>
'''


def write_all(write, out: Path = ROOT) -> None:
    write(out / "portfolio" / "index.html", render_page())
    write(out / "portfolio" / "view.html", render_page(public=True))
    write(out / "notebook" / "index.html", NOTEBOOK_REDIRECT)


def _e(s) -> str:
    return html.escape(str(s), quote=True)
