#!/usr/bin/env python3
"""portfolio.py — the Portfolio page and the degree map it reads.

    degree_map()      -> dict: every day in Path order, every course's made
                         thing and outcomes, the reflection questions
    render_page()     -> HTML for portfolio/index.html (the map embedded)
    write_all(write, out)

The Portfolio is assembled in the browser (assets/js/portfolio.js) from the
learner's own answers, read from this device or, signed in, from the account.
Nothing about a learner is in this file or on the server-rendered page: the
page carries only the shape of the degree, and the learner's words never leave
their browser except to their own account.

Three editions render from one store (PLAN.md section 15):
  Volumes   one book per semester
  Short     the judging document: commitment, the Question, the made things
  Expanded  everything, in order
"""
from __future__ import annotations

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

OUTCOME_NAMES = {
    "judgment": "Judgment",
    "intelligence": "Command of Intelligence",
    "craft": "Workmanship",
    "articulation": "Articulation",
    "breadth": "Breadth of Mind",
}


def degree_map() -> dict:
    import degree_path
    import publishing
    import reflections
    from catalog import load_catalog

    cat = load_catalog()
    refl = reflections.load()
    courses = {}
    for c in cat["courses"]:
        courses[c["dir"]] = {
            "code": c["code"],
            "name": c.get("display") or c["name"],
            "catalog": c["name"],
            "semester": c.get("semester"),
            "thread": c.get("thread"),
            "made": " ".join(str(c.get("artifact", "")).split()),
            "outcomes": [OUTCOME_NAMES.get(o, o) for o in c.get("outcomes", [])],
            "concentrations": c.get("concentrations", []),
        }

    days = []
    for s in degree_path.sequence():
        if s.kind != "day":
            continue
        c = s.course or {}
        q = ""
        info_q = None
        md = ROOT / "courses" / c["dir"] / f"day-{s.n:02d}.md"
        if md.exists():
            import frontmatter
            meta, _ = frontmatter.parse(md.read_text(encoding="utf-8"))
            info_q = meta.get("question")
        if info_q:
            q = str(info_q)
        else:
            import arcs
            arc = arcs.load_arc(ROOT / "courses" / c["dir"])
            a = arc.day(s.n) if arc else None
            q = a.question if a else ""
        # Compact rows: semester, week, weekday label, course dir, day, title, question.
        days.append([s.semester, s.week, s.label, c["dir"], s.n, s.title, q])

    gates_q = [{"id": q["id"], "text": q["text"]} for q in refl["gates"]["questions"]]
    return {
        "outcomes": list(OUTCOME_NAMES.values()),
        "semesters": [{"n": n, "label": publishing.semester_label(n)} for n in range(1, 9)],
        "courses": courses,
        "begin": {"lesson": refl["begin"]["lesson"],
                  "questions": [{"id": q["id"], "text": q["text"]} for q in refl["begin"]["questions"]]},
        "gates": [{"n": n, "lesson": refl["gates"]["lesson"].format(n=n), "questions": gates_q}
                  for n in range(1, 9)],
        "question": "What does education mean to you?",
        "days": days,
    }


