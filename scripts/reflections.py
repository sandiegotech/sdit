#!/usr/bin/env python3
"""reflections.py — Day 0 and the gates, from knowledge/reflections.yaml.

    render_begin()        -> HTML for begin/index.html
    render_gate(n)        -> HTML for gates/semester-n/index.html
    write_all(write)      -> writes all nine pages through the given writer

Answers on these pages are saved by assets/js/student-work.js exactly like a
day's answer: under the page's lesson id (meta sdit-lesson) and the question
id (data-sdit-answer). The Commitment is stored the same way, under /begin
with the heading "commitment" and the date as its value. Nothing here is
gated: every page is readable by anyone.
"""
from __future__ import annotations

import html
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "knowledge" / "reflections.yaml"


def load() -> dict:
    import yaml

    return yaml.safe_load(SOURCE.read_text(encoding="utf-8"))


def _e(s) -> str:
    return html.escape(str(s), quote=True)


def _shell(title: str, description: str, lesson: str, body: str, depth: int) -> str:
    up = "../" * depth
    return f'''<!doctype html>
<!-- Generated by scripts/reflections.py from knowledge/reflections.yaml — do not edit by hand -->
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>{_e(title)} — SDIT</title>
  <meta name="description" content="{_e(description)}">
  <meta name="sdit-lesson" content="{_e(lesson)}" />
  <link rel="stylesheet" href="{up}assets/site.css" />
  <script src="{up}assets/js/site-paths.js" defer></script>
  <script src="{up}assets/js/includes.js" defer></script>
</head>
<body class="charter-page reflection-page">
  <div data-include="/partials/header.html"></div>

  <main>
{body}
  </main>

  <div data-include="/partials/footer.html"></div>
</body>
</html>
'''


def _question(qid: str, text: str) -> str:
    return f'''          <div class="reflection-q">
            <h3>{_e(text)}</h3>
            <div class="answer-slot" data-sdit-answer="{_e(qid)}" data-question="{_e(text)}"></div>
          </div>'''


NOSCRIPT = ('          <noscript><p class="answer-hint">Your answers are kept by your browser. '
            'Turn on JavaScript to write them here.</p></noscript>')


def _next_card(eyebrow: str, title: str, sub: str, href: str | None) -> str:
    inner = (f'<span class="lesson-tomorrow-eyebrow">{_e(eyebrow)}</span>'
             f'<strong>{_e(title)}</strong>'
             + (f'<span class="lesson-tomorrow-sub">{_e(sub)}</span>' if sub else "")
             + f'<span class="lesson-tomorrow-cta">{"Continue →" if href else "Coming"}</span>')
    if href:
        return f'<a class="lesson-tomorrow-card" href="{_e(href)}">{inner}</a>'
    return f'<div class="lesson-tomorrow-card is-upcoming">{inner}</div>'


def render_begin(data: dict | None = None) -> str:
    import catalog

    data = data or load()
    c, b = data["commitment"], data["begin"]
    paras = "\n".join(f"          <p>{_e(' '.join(p.split()))}</p>" for p in c["paragraphs"])
    questions = "\n".join(_question(q["id"], q["text"]) for q in b["questions"])

    first = ROOT / "courses" / "HUM-101"
    info = catalog.day_info(first, 1)
    next_title = info[0] if info else "The Ancient World, Day 1"
    card = _next_card(b["next"]["eyebrow"], next_title, "Mon · HUM 101 · The Ancient World", b["next"]["href"])

    body = f'''    <header class="page-header">
      <div class="frame">
        <span class="page-header__eyebrow">{_e(b["eyebrow"])}</span>
        <h1 class="page-header__title">{_e(b["title"])}<em>.</em></h1>
        <p class="page-header__meta">the Commitment · three questions · then Day 1</p>
      </div>
    </header>

    <section class="article" id="commitment">
      <div class="frame article-grid">
        <div class="article-label">{_e(c["heading"])}</div>
        <div class="article-body commitment" data-sdit-commit>
{paras}
          <div class="commit-actions" data-commit-actions>
            <button class="learn-cta" type="button" data-commit>{_e(c["commit_label"])}</button>
            <a class="learn-cta learn-cta--ghost" href="{_e(c["look_href"])}">{_e(c["look_label"])}</a>
          </div>
          <p class="commit-done" data-commit-done data-template="{_e(c["committed_line"])}" hidden></p>
          <p class="commit-foot"><a href="{_e(c["footnote_href"])}">{_e(c["footnote"])} →</a></p>
        </div>
      </div>
    </section>

    <section class="article" id="questions" data-after-commit>
      <div class="frame article-grid">
        <div class="article-label">Three Questions<span class="num">Kept in your Notebook</span></div>
        <div class="article-body">
          <p>{_e(" ".join(b["intro"].split()))}</p>
{NOSCRIPT}
{questions}
          <div class="lesson-next" style="margin-top:2.5rem;">
            {card}
          </div>
        </div>
      </div>
    </section>
'''
    return _shell("Begin", "Day 0: the Commitment, and three questions you will answer again at the end of every semester.",
                  b["lesson"], body, depth=1)


def render_gate(n: int, data: dict | None = None) -> str:
    import degree_path
    import publishing

    data = data or load()
    g = data["gates"]
    lesson = g["lesson"].format(n=n)
    label = publishing.semester_label(n)
    qs = []
    for q in g["questions"]:
        text = q["text"]
        if n == 8 and q["id"] == "education":
            text = g["final"]["education_text"]
            qs.append(f'''          <div class="reflection-recall">
            <p class="reflection-recall-label">{_e(g["final"]["recall_label"])}</p>
            <blockquote data-sdit-recall="/begin::education"></blockquote>
          </div>''')
        qs.append(_question(q["id"], text))

    # Where the Path goes after this gate.
    nxt = None
    if n < 8:
        for s in degree_path.sequence():
            if s.kind == "day" and s.semester == n + 1 and not s.studio:
                nxt = s
                break
    if nxt:
        c = nxt.course or {}
        sub = f"{nxt.label} · {c.get('code', '')} · {c.get('display') or c.get('name', '')}"
        if nxt.published:
            card = _next_card(f"Semester {n + 1} begins", nxt.title, sub, nxt.href)
        else:
            when = publishing.long_date(nxt.publishes) if nxt.publishes else "soon"
            card = _next_card(f"Semester {n + 1} begins", nxt.title, f"{sub} · publishes {when}", None)
    else:
        # The Portfolio arrives in a later step; until its source exists the
        # card names it without linking.
        portfolio = (ROOT / "scripts" / "portfolio.py").exists()
        card = _next_card("The end of the Path", "Your Portfolio", "Every answer and every made thing, as a book.",
                          "/portfolio/" if portfolio else None)

    body = f'''    <header class="page-header">
      <div class="frame">
        <span class="page-header__eyebrow">{_e(g["eyebrow"])} · Semester {n}</span>
        <h1 class="page-header__title">End of Semester {n}<em>.</em></h1>
        <p class="page-header__meta">{_e(label)} · five questions · kept in your Notebook</p>
      </div>
    </header>

    <section class="article" id="gate">
      <div class="frame article-grid">
        <div class="article-label">The Gate<span class="num">Semester {n}</span></div>
        <div class="article-body">
          <p class="gate-commitment" data-sdit-commitment-line data-semester="{n}"></p>
          <p>{_e(" ".join(g["intro"].format(n=n).split()))}</p>
{NOSCRIPT}
{chr(10).join(qs)}
          <div class="lesson-next" style="margin-top:2.5rem;">
            {card}
          </div>
          <p class="lesson-selfpace"><a href="/curriculum/day-by-day.html">The whole Path →</a></p>
        </div>
      </div>
    </section>
'''
    return _shell(f"The Gate · Semester {n}",
                  f"The end of Semester {n}: the Day 0 questions again, what you made, and what changed.",
                  lesson, body, depth=2)


def write_all(write, out: Path = ROOT) -> None:
    data = load()
    write(out / "begin" / "index.html", render_begin(data))
    for n in range(1, 9):
        write(out / "gates" / f"semester-{n}" / "index.html", render_gate(n, data))
